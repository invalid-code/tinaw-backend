-- ---------------------------------------------------------------------------
-- Stations
-- ---------------------------------------------------------------------------
create table if not exists public.stations (
  id                        text primary key,
  station_number            text not null unique,
  name                      text not null,
  hub_name                  text not null,
  location_subtitle         text not null,
  catchment                 text not null,
  is_primary                boolean not null default false,
  status                    text not null check (status in ('good', 'fair', 'monitoring', 'alert')),
  status_label              text not null,
  score_display             text not null default 'XX',
  calculated_score          integer not null check (calculated_score between 0 and 100),
  score_note                text not null default '',
  clarity_percent           numeric(5, 1) not null check (clarity_percent between 0 and 100),
  recirculation_active      boolean not null default false,
  recirculation_status      text not null default '',
  recirc_cycles_done        integer not null default 0 check (recirc_cycles_done >= 0),
  updated_ago               text not null default '',
  last_updated_timestamp    text not null default '',
  hero_image                text not null default '',
  map_x                     numeric(5, 2) not null,
  map_y                     numeric(5, 2) not null,
  lat                       double precision not null,
  lng                       double precision not null,
  assessment_summary        text not null default '',
  evaluated_parameters_text text not null default '',
  reference_assessment_text text not null default '',
  last_verification_date    text not null default '',
  created_at                timestamptz not null default now(),
  updated_at                timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Sensor parameters (pH, turbidity, TDS, temperature, ...)
-- ---------------------------------------------------------------------------
create table if not exists public.station_parameters (
  id              bigint generated by default as identity primary key,
  station_id      text not null references public.stations(id) on delete cascade,
  name            text not null,
  parameter_key   text not null check (parameter_key in ('ph', 'turbidity', 'tds', 'temperature')),
  value           numeric not null,
  unit            text not null,
  status          text not null,
  status_type     text not null check (status_type in ('good', 'fair', 'warning', 'info')),
  target_label    text not null,
  min_value       numeric not null,
  max_value       numeric not null,
  optimal_min     numeric,
  optimal_max     numeric,
  target_max      numeric,
  current_percent numeric(5, 1) not null check (current_percent between 0 and 100),
  description     text not null default '',
  sort_order      integer not null default 0,
  unique (station_id, parameter_key)
);

create index if not exists station_parameters_station_id_idx
  on public.station_parameters (station_id);

-- ---------------------------------------------------------------------------
-- Historical readings for the 24h / 7d / 30d charts
-- ---------------------------------------------------------------------------
create table if not exists public.station_history (
  id            bigint generated by default as identity primary key,
  station_id    text not null references public.stations(id) on delete cascade,
  time_range    text not null check (time_range in ('24h', '7d', '30d')),
  label         text not null,
  full_time     text not null,
  score         integer not null check (score between 0 and 100),
  threshold_min integer not null,
  threshold_max integer not null,
  turbidity     numeric not null,
  ph            numeric not null,
  tds           numeric not null,
  sort_order    integer not null default 0,
  unique (station_id, time_range, sort_order)
);

create index if not exists station_history_station_range_idx
  on public.station_history (station_id, time_range, sort_order);

-- ---------------------------------------------------------------------------
-- Row Level Security: public read-only access
-- ---------------------------------------------------------------------------
alter table public.stations enable row level security;
alter table public.station_parameters enable row level security;
alter table public.station_history enable row level security;

drop policy if exists "Public read stations" on public.stations;
create policy "Public read stations"
  on public.stations for select
  to anon, authenticated
  using (true);

drop policy if exists "Public read station parameters" on public.station_parameters;
create policy "Public read station parameters"
  on public.station_parameters for select
  to anon, authenticated
  using (true);

drop policy if exists "Public read station history" on public.station_history;
create policy "Public read station history"
  on public.station_history for select
  to anon, authenticated
  using (true);

grant select on public.stations, public.station_parameters, public.station_history
  to anon, authenticated;
