-- TinAw Water Quality Network - link raw sensor telemetry to stations
-- Run this in the Supabase Dashboard -> SQL Editor after
-- 20261106000000_tinaw_schema.sql.
--
-- IMPORTANT: change the station_id in step 2 if esp32_water_sensor_01 is
-- deployed at a different station.

-- ---------------------------------------------------------------------------
-- Raw telemetry (already exists in the hosted project; created here so a
-- fresh database can be reproduced from the repo).
-- ---------------------------------------------------------------------------
create table if not exists public.sensor_data (
  id          bigint generated by default as identity primary key,
  device_id   text not null,
  turbidity   numeric,
  ph          numeric,
  temperature numeric,
  tds         numeric,
  recorded_at timestamptz not null default now()
);

create index if not exists sensor_data_device_recorded_idx
  on public.sensor_data (device_id, recorded_at desc);

-- ---------------------------------------------------------------------------
-- Device registry: maps a physical device to the station it monitors.
-- ---------------------------------------------------------------------------
create table if not exists public.devices (
  device_id  text primary key,
  station_id text not null references public.stations(id) on delete cascade,
  label      text not null default '',
  is_active  boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists devices_station_id_idx
  on public.devices (station_id);

-- Register the ESP32 currently writing to sensor_data.
-- Change 'kalunasan' if this device belongs to another station.
insert into public.devices (device_id, station_id, label)
values ('esp32_water_sensor_01', 'kalunasan', 'Kalunasan ESP32 water sensor')
on conflict (device_id) do update
set station_id = excluded.station_id,
    label = excluded.label,
    updated_at = now();

-- Every new sensor row must belong to a registered device.
-- NOT VALID lets existing historical rows through; new rows are checked.
do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'sensor_data_device_id_fkey'
      and conrelid = 'public.sensor_data'::regclass
  ) then
    alter table public.sensor_data
      add constraint sensor_data_device_id_fkey
      foreign key (device_id) references public.devices(device_id)
      on delete cascade
      not valid;
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- Public read access for the dashboard.
--
-- We intentionally DO NOT enable RLS on sensor_data here: it may already be
-- enabled, and changing that state could block the ESP32/MQTT bridge inserts.
-- The select policy below takes effect if RLS is already enabled. If your
-- bridge writes with the publishable/anon key, also add an insert policy:
--
--   create policy "Device insert sensor data"
--     on public.sensor_data for insert
--     to anon
--     with check (device_id = 'esp32_water_sensor_01');
--
-- (service_role bypasses RLS, so no insert policy is needed for a server-side
-- bridge.)
-- ---------------------------------------------------------------------------
alter table public.devices enable row level security;

drop policy if exists "Public read devices" on public.devices;
create policy "Public read devices"
  on public.devices for select
  to anon, authenticated
  using (true);

drop policy if exists "Public read sensor data" on public.sensor_data;
create policy "Public read sensor data"
  on public.sensor_data for select
  to anon, authenticated
  using (true);

grant select on public.devices, public.sensor_data to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Latest valid value for each parameter, per device.
--
-- The ESP32 currently reports sentinel values for missing sensors:
--   pH = -1, temperature = -127, turbidity = NULL
-- Each parameter is filtered independently, so a broken sensor does not
-- discard the valid readings from the others.
-- ---------------------------------------------------------------------------
create or replace view public.latest_sensor_readings
with (security_invoker = true)
as
select
  d.station_id,
  sd.device_id,
  max(sd.recorded_at) as last_recorded_at,
  (array_agg(sd.ph order by sd.recorded_at desc)
    filter (where sd.ph between 0 and 14))[1] as ph,
  (array_agg(sd.turbidity order by sd.recorded_at desc)
    filter (where sd.turbidity >= 0))[1] as turbidity,
  (array_agg(sd.tds order by sd.recorded_at desc)
    filter (where sd.tds >= 0))[1] as tds,
  (array_agg(sd.temperature order by sd.recorded_at desc)
    filter (where sd.temperature between -5 and 60))[1] as temperature
from public.sensor_data sd
join public.devices d on d.device_id = sd.device_id
group by d.station_id, sd.device_id;

grant select on public.latest_sensor_readings to anon, authenticated;
